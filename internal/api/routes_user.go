package api

import (
	"github.com/go-chi/chi/v5"

	"github.com/zachcurry13/novelcheck/internal/auth"
	"github.com/zachcurry13/novelcheck/internal/store"
)

// userRoutes are the routes for any signed-in person (behind friendGuard): their own account, books, reading and
// Kindle, as opposed to the modules an admin can turn off and the manager and admin tools.
func (s *Server) userRoutes(r chi.Router) {
	r.Get("/me", s.handleMe)
	r.Delete("/me/view-as", s.handleStopViewing)                                     // back to the admin's own account
	r.Post("/me/events/{id}/books/{book}/claim", friendOnly(s.handleClaimEventBook)) // into her own library
	r.Post("/me/import", friendOnly(s.handleImportDrive))                            // her Goodreads list, into her library
	r.Get("/activity/status", s.handleActivityStatus)
	r.Post("/activity/events", s.handleActivityEvents)
	r.Put("/me/pin", s.handleMyPIN)
	r.Put("/me/password", s.handleChangePassword)
	r.Put("/me/delivery", s.handleUpdateDelivery)
	r.Put("/me/guide-seen", s.handleGuideSeen)
	r.Put("/me/start-page", s.handleStartPage)
	r.With(auth.RequireManager).Put("/me/claim-library", s.handleClaimLibrary) // where my event claims go
	r.Put("/me/appearance", s.handleAppearance)
	r.Get("/me/searches", s.handleSearches)
	r.Post("/me/searches", s.handleAddSearch)
	r.Delete("/me/searches", s.handleClearSearches)
	r.Get("/me/opds", s.handleMyOPDS)
	r.Post("/me/opds/reset", s.handleResetMyOPDS)
	r.Post("/me/bug-report", s.handleBrowserReport)
	r.Get("/me/kosync", s.handleMyKosync)
	r.Post("/me/kosync", s.handleMyKosync)
	r.Get("/me/koplugin.zip", s.handleMyPluginZip)
	r.Get("/me/kindle-app.zip", s.handleMyKindleAppZip)
	r.Get("/me/content-prefs", s.handleContentPrefs) // Hide / Heads-up / Don't mention, per person
	r.Put("/me/content-prefs", s.handleContentPrefs)
	r.Put("/me/device-link", s.handleDeviceLink)  // the plugin and the app are one Kindle
	r.Post("/upload/ebook", s.handleFamilyUpload) // drag and drop for admins and people an admin allowed
	r.Post("/upload/fix", s.handleUploadFix)
	r.With(s.cached).Get("/home", s.handleHome) // 2.0: the start screen
	r.Post("/home/snooze", s.handleSnooze)
	r.Get("/requests", s.handleRequests) // ask for a book; a parent answers
	r.Post("/requests", s.handleAddRequest)
	r.Post("/requests/{id}/decide", s.handleDecideRequest)
	r.Post("/books/{id}/disagree", s.handleDisagree) // a grown-up's own level for a book
	r.With(s.cached).Get("/me/kindle-library", s.handleKindleLibrary)
	r.With(s.cached).Get("/me/kindles", s.handleKindles)
	r.Get("/me/left", s.handleMyLeft) // books that left your e-reader, and the ones you removed from your library
	r.Post("/me/left", s.handleMyLeft)
	r.Delete("/me/hidden-books/{id}", s.handleUnhide)
	r.Put("/me/kindle-autoadd", s.handleKindleAutoAdd)
	r.Get("/me/kindle-books", s.handleKindleBooks)
	r.Post("/me/kindle-match", s.handleKindleMatch)
	r.Get("/me/koreader-books", s.handleMyKOReaderBooks)
	r.Get("/me/reading-sync", s.handleMyReadingSync)
	r.Post("/me/dav/tidy", s.handleDAVTidy)
	r.With(s.cached).Get("/me/reading-stats", s.handleMyReadingStats)
	r.Get("/me/sharing", s.handleMySharing)
	r.Put("/me/sharing", s.handleMySharing)
	r.Get("/readers", s.handleReaders)
	r.Get("/readers/{id}/stats", s.handleReaderStats)
	r.Get("/me/libby", s.handleLibbyLibrary)
	r.Delete("/me/libby/{key}", s.handleLibbyRemove)
	r.Post("/libby/audio", s.handleLibbyAudioKept)
	r.Post("/me/libby/scan", s.handleLibbyScan)
	r.Put("/me/libby", s.handleLibbySetLibrary)
	r.Get("/books/{id}/libby", s.handleBookLibby)
	r.Put("/books/{id}/rating", s.handleSetRating)
	r.Put("/books/{id}/finished", s.handleSetFinished)
	r.Post("/libby/check", s.handleLibbyCheck)
	r.Get("/libby/search", s.handleLibbySearch)
	r.Get("/libby/cover", s.handleLibbyCover)
	r.Post("/libby/add", s.handleLibbyAdd)
	r.Get("/me/hardcover", s.handleHardcoverStatus)
	r.Put("/me/hardcover", s.handleHardcoverConnect)
	r.Post("/me/hardcover/sync", s.handleHardcoverSync)
	r.Get("/me/kindle-tasks", s.handleKindleTasks) // the Kindle remote (Settings → Kindle & KOReader): your own Kindles
	r.Post("/me/kindle-tasks", s.handleKindleTasks)
	r.Delete("/me/kindle-tasks/{id}", s.handleKindleTaskCancel)
	r.Put("/me/hardcover/push", s.handleHardcoverPush)

	r.With(s.cached).Get("/books", s.handleListBooks)
	r.With(s.cached).Get("/books/facets", s.handleBookFacets)
	r.Get("/books/states", s.handleBookStates)
	r.With(s.cached).Get("/collections", s.handleListCollections)
	r.Get("/series", s.handleSeriesList)
	r.Get("/series/one", s.handleSeries)
	r.Post("/series/fill", s.handleSeriesFill)
	r.Get("/collections/{id}", s.handleGetCollection)
	r.Get("/events", s.handleListEvents)
	r.Get("/events/{id}", s.handleGetEvent)
	r.Post("/books/bulk", s.handleBulkBooks)
	r.With(s.cached).Get("/books/{id}", s.handleGetBook)
	r.Get("/books/{id}/download", s.handleDownload)
	r.Get("/books/{id}/position", s.handleReaderPosition)
	r.Put("/books/{id}/position", s.handleReaderPosition)
	r.Get("/books/{id}/bookmarks", s.handleBookmarks)
	r.Get("/books/{id}/hardcover", s.handleHCMore)
	r.Get("/books/{id}/highlights", s.handleBookHighlights)
	r.Get("/me/summaries", s.handleSummaryPrefs)
	r.Put("/me/summaries", s.handleSummaryPrefs)
	r.Post("/books/{id}/bookmarks", s.handleBookmarks)
	r.Delete("/books/{id}/bookmarks", s.handleBookmarks)
	r.Get("/books/{id}/audio/{ino}", s.handleAudioStream)
	r.Get("/books/{id}/listen", s.handleListen)
	r.Put("/books/{id}/listen/progress", s.handleListenProgress)
	r.Post("/books/{id}/listen/bookmark", s.handleListenBookmark)
	r.Delete("/books/{id}/listen/bookmark", s.handleListenBookmark)
	r.Get("/listening", s.handleListening)
	r.Get("/me/audiobookshelf", s.handleMyABS)
	r.Put("/me/audiobookshelf", s.handleLinkABS)
	r.Delete("/me/audiobookshelf", s.handleUnlinkABS)
	r.Get("/books/{id}/cover", s.handleCover)
	r.Get("/books/{id}/cover-options", s.handleCoverOptions) // Change cover: your own, or (admins) everyone's
	r.Post("/books/{id}/cover", s.handleSetCover)
	r.Delete("/books/{id}/cover", s.handleResetCover)
	r.Get("/cover-preview", s.handleCoverPreview)
	r.Post("/books/{id}/cover-report", s.handleReportCover)
	r.Post("/books/{id}/delete-request", s.handleRequestDelete)
	r.Delete("/books/{id}/delete-request", s.handleCancelDelete)
	r.With(s.cached).Get("/catalogs", s.handleListCatalogs)
	r.Put("/catalogs/{id}/shown", s.handleCatalogShown)
	r.Get("/age-groups", s.handleAgeGroups)
	r.Get("/updates", s.handleUpdates)
	r.Get("/flags", s.handleListFlags)
	r.Get("/content", s.handleContentCatalog)
	r.With(s.requireModule(store.KeyModuleDiscover, "Discover"), s.cached).Get("/discover", s.handleDiscover)
	r.Post("/books/{id}/wish", s.handleAddWish)
	r.Delete("/books/{id}/wish", s.handleRemoveWish)
	r.Get("/wishlist", s.handleWishlist)
	r.Get("/books/{id}/deep-scan", s.handleBookDeepScan)
	r.Post("/books/{id}/deep-scan", s.handleStartDeepScan)
	r.Get("/push", s.handlePushStatus)
	r.Post("/push/subscribe", s.handlePushSubscribe)
	r.Post("/push/unsubscribe", s.handlePushUnsubscribe)
	r.Post("/push/test", s.handlePushTest)
	r.Post("/problems", s.handleReportProblem)
}
